export type Locale = "en" | "pl";
const reverse = Object.fromEntries(
  Object.entries(english).map(([pl, en]) => [en, pl]),
);
const keys = Object.keys(english).sort((a, b) => b.length - a.length);
export function translate(text: string, locale: Locale): string {
  if (locale === "pl") return reverse[text] ?? text;
  if (english[text]) return english[text];
  // Composite validation messages and accessible names retain IDs and user titles.
  if (text.includes("\n"))
    return text
      .split("\n")
      .map((line) => translate(line, locale))
      .join("\n");
  const prefix = keys.find(
    (key) => text.startsWith(key + " ") || text.endsWith(": " + key),
  );
  const result = prefix
    ? text.startsWith(prefix + " ")
      ? english[prefix] + text.slice(prefix.length)
      : text.slice(0, -prefix.length) + english[prefix]
    : text;
  return result
    .replace(/(\d+) ujęć/g, "$1 shots")
    .replace(/(\d+) slajdów/g, "$1 slides")
    .replace(/(\d+) sekund/g, "$1 seconds")
    .replace(/ w górę$/, " up")
    .replace(/ w dół$/, " down");
}
